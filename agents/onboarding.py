def build_style_description(tone: str, references: str) -> str:
    """Собирает краткое «описание стиля» из тона и референс-аккаунтов.

    Используется и при онбординге (handlers/start.py), и при редактировании
    профиля (handlers/menu.py), чтобы поле style_description оставалось
    согласованным с tone/reference_accounts. Пустые части опускаются.
    """
    parts = []
    if tone:
        parts.append(f"Тон: {tone}")
    if references:
        parts.append(f"Ориентиры: {references}")
    return ". ".join(parts)


def build_summary(profile: dict) -> str:
    """Формирует финальное резюме профиля (дословно по spec.md §7.1).

    profile — dict с ключами niche, audience (или target_audience), tone,
    accounts (или reference_accounts).
    """
    niche = profile.get("niche", "")
    # Поддерживаем оба именования ключа аудитории
    audience = profile.get("audience") or profile.get("target_audience", "")
    tone = profile.get("tone", "")
    # Поддерживаем оба именования ключа референсов
    accounts = profile.get("accounts") or profile.get("reference_accounts", "")

    return (
        "Профиль сохранён ✓\n\n"
        f"Ниша: {niche}\n"
        f"Аудитория: {audience}\n"
        f"Тон: {tone}\n"
        f"Ориентиры: {accounts}\n\n"
        "Можем начинать. Напиши: 'пост про [тема]' или 'рилс про [тема]'"
    )
