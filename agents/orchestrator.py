"""Оркестратор: определяет intent пользователя из свободного текста и
выделяет тему запроса (spec.md §6.1).

Чистый модуль без зависимостей от aiogram — содержит только функции разбора
текста. Используется хэндлером handlers/message.py для маршрутизации.

Интенты:
  "post"  — написать пост (Фаза 6);
  "reel"  — сценарий Reels (Фаза 7);
  "plan"  — контент-план (V2, пока недоступно);
  "trend" — тренды/анализ конкурентов (V2, пока недоступно);
  "unknown" — намерение не распознано → вежливое уточнение.
"""

from utils.logger import get_logger

logger = get_logger(__name__)

# Карта интентов и ключевых фраз (ДОСЛОВНО по spec.md §6.1).
# plan/trend помечены как V2 — включены в карту, но роутятся в «пока недоступно».
INTENT_MAP: dict[str, list[str]] = {
    "post": ["напиши пост", "пост про", "сделай пост", "написать пост"],
    "reel": ["рилс", "reels", "сценарий", "видео про", "сделай рилс"],  # V2-нет: post/reel живые
    "plan": ["контент-план", "план на", "планирование"],  # V2
    "trend": ["тренды", "что популярно", "конкуренты", "анализ"],  # V2
}

# Текст вежливого уточнения при нераспознанном намерении (spec.md §6.1).
CLARIFY_TEXT = "Напиши пост, сценарий Reels или что-то другое?"

# Порядок проверки интентов важен: reel проверяем раньше post, чтобы
# «сделай сценарий поста» / «рилс про пост» уходили в reel (ключ «сценарий»,
# «рилс» — более специфичные). Затем post, затем V2-интенты.
_INTENT_PRIORITY: tuple[str, ...] = ("reel", "post", "plan", "trend")

# Командные слова/фразы, которые нужно вырезать при выделении темы.
# Сначала идут длинные многословные фразы, затем одиночные слова — порядок
# важен, чтобы «напиши пост про» удалялось целиком до «пост»/«про».
_TOPIC_NOISE: tuple[str, ...] = (
    "напиши пост про",
    "напиши пост на тему",
    "напиши пост о",
    "написать пост про",
    "сделай пост про",
    "сделай рилс про",
    "сделай рилс на тему",
    "сделай сценарий про",
    "сделай сценарий для",
    "сценарий рилс про",
    "сценарий reels про",
    "видео про",
    "рилс про",
    "reels про",
    "пост про",
    "напиши пост",
    "написать пост",
    "сделай пост",
    "сделай рилс",
    "сделай сценарий",
    "сделай видео",
    "напиши",
    "сделай",
    "сценарий",
    "рилс",
    "reels",
    "пост",
    "видео",
    "про",
    "на тему",
    "о том",
    "об",
    "о",
)


def detect_intent(text: str) -> str:
    """Определяет intent по ключевым фразам из INTENT_MAP.

    Нормализует текст (lower + strip), затем ищет вхождение ключевых фраз.
    Возвращает один из: "post" | "reel" | "plan" | "trend" | "unknown".

    Приоритет (_INTENT_PRIORITY): reel → post → plan → trend, чтобы более
    специфичные «сценарий»/«рилс» побеждали общее «пост».
    """
    if not text:
        return "unknown"

    normalized = text.lower().strip()

    for intent in _INTENT_PRIORITY:
        for phrase in INTENT_MAP[intent]:
            if phrase in normalized:
                logger.info("detect_intent: '%s' → %s (фраза: '%s')", text, intent, phrase)
                return intent

    logger.info("detect_intent: '%s' → unknown", text)
    return "unknown"


def extract_topic(text: str, intent: str) -> str:
    """Выделяет тему запроса, убирая командные слова.

    Пример: «Напиши пост про осенний уход за кожей» → «осенний уход за кожей».
    Если после вычистки командных слов ничего не осталось — возвращает пустую
    строку (вызывающий код попросит уточнить тему).

    intent передаётся для возможной интент-специфичной логики в будущем; сейчас
    список шумовых слов общий для post/reel.
    """
    if not text:
        return ""

    result = text.strip()
    lowered = result.lower()

    # Идём по шумовым фразам (от длинных к коротким) и срезаем их с НАЧАЛА темы,
    # повторяя проход, пока в начале строки остаются командные слова.
    # ВАЖНО: срезаем только по границе слова — фраза должна заканчиваться концом
    # строки или разделителем, иначе «о» вырежет начало слова «осенний».
    _SEPARATORS = " :-—,.\t"
    changed = True
    while changed:
        changed = False
        result = result.strip()
        lowered = result.lower()
        for phrase in _TOPIC_NOISE:
            if not lowered.startswith(phrase):
                continue
            rest = result[len(phrase):]
            # Граница слова: после фразы конец строки или разделитель.
            if rest == "" or rest[0] in _SEPARATORS:
                result = rest.lstrip(_SEPARATORS).strip()
                changed = True
                break

    return result.strip()
