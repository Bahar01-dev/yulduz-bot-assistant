"""Инструкции формата для контент-плана (V2, spec.md §18 «Контент-план»).

Пользователь выбирает период (неделя/месяц) → один вызов LLM возвращает план
публикаций строго в парсимом виде: пронумерованные строки с темой и форматом
(пост/Reels). Профиль бренда и история тем приходят через build_system_prompt
(система не повторяет уже написанные темы — §13.2).

Маркер PLAN_MARKER отделяет тело плана; форматтер (utils.formatter.format_plan)
парсит по нему. НЕ менять без правки парсера.
"""

# Temperature для плана: ниже, чем у постов — нужен предсказуемый структурный список.
PLAN_TEMPERATURE = 0.6

# Маркер начала плана (форматтер парсит по нему).
PLAN_MARKER = "ПЛАН:"

# Поддерживаемые периоды → (русское название, число идей, подсказка по структуре).
PERIODS: dict[str, dict] = {
    "week": {
        "title": "неделю",
        "items": 7,
        "structure": "РОВНО 7 идей — по одной на каждый день недели (Пн–Вс).",
    },
    "month": {
        "title": "месяц",
        "items": 12,
        "structure": (
            "РОВНО 12 идей, сгруппированных по 4 неделям (по 3 идеи на неделю). "
            "Перед каждой группой ставь строку «Неделя 1», «Неделя 2» и т.д."
        ),
    },
}
DEFAULT_PERIOD = "week"


def period_title(period: str) -> str:
    """Русское название периода в винительном падеже (на неделю/на месяц)."""
    return PERIODS.get(period, PERIODS[DEFAULT_PERIOD])["title"]


def plan_instruction(period: str = DEFAULT_PERIOD) -> str:
    """Инструкция формата контент-плана на выбранный период.

    Жёсткий формат: после PLAN_MARKER — пронумерованные строки
    «N. <Тема> | <Формат> — <идея хука>». Формат ∈ {Пост, Reels}.
    """
    cfg = PERIODS.get(period, PERIODS[DEFAULT_PERIOD])
    return f"""\
ЗАДАЧА: составь контент-план на {cfg['title']} для Instagram-блога в нише и тоне профиля.

{cfg['structure']}
Идеи не должны повторять уже написанные темы из истории.
Чередуй форматы: примерно поровну Пост и Reels.
Каждая идея — конкретная и цепляющая, а не общая («про мотивацию» — плохо,
«3 ошибки новичков, из-за которых клиенты уходят» — хорошо).

ФОРМАТ ВЫВОДА (строго, без вступлений и комментариев):

{PLAN_MARKER}
1. <Тема идеи> | <Пост или Reels> — <короткая идея хука>
2. <Тема идеи> | <Пост или Reels> — <короткая идея хука>
[… и так далее по числу идей …]

Выводи только строки плана после маркера {PLAN_MARKER} и ничего больше.
Для месяца перед каждой группой из 3 идей ставь отдельную строку «Неделя N»."""
