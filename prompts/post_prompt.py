"""Инструкции формата для постов Instagram (spec.md §9.1, §9.3, §13.1).

Двухшаговая генерация:
  ШАГ 1 — hooks_instruction(): отдельный вызов LLM, возвращает РОВНО 3 хука
          в легко парсимом виде (пронумерованный список HOOK_1/2/3).
  ШАГ 2 — post_format_instruction(selected_hook): отдельный вызов LLM по
          выбранному хуку, возвращает полный пост строго в формате §9.1 с
          явными маркерами секций (POST:/CTA:/ХЭШТЕГИ:/ЧЕКЛИСТ:), чтобы
          formatter Фазы 6 распарсил без угадывания структуры.

Каждая из этих инструкций подставляется в {format_instructions} системного
промпта из style_builder.build_system_prompt().
"""

# Temperature для генерации постов (§13.1)
POST_TEMPERATURE = 0.7

# Маркеры секций — formatter (Фаза 6) парсит по ним. НЕ менять без правки парсера.
HOOK_PREFIX = "HOOK_"  # ШАГ 1: HOOK_1 / HOOK_2 / HOOK_3
POST_MARKER = "POST:"
CTA_MARKER = "CTA:"
HASHTAGS_MARKER = "ХЭШТЕГИ:"
CHECKLIST_MARKER = "ЧЕКЛИСТ:"


def hooks_instruction(topic: str) -> str:
    """ШАГ 1: инструкция «верни ровно 3 варианта хука» по теме.

    Формат вывода жёсткий: три строки с префиксом HOOK_N, чтобы парсинг был
    тривиальным (по строкам). Никакого вступления и пояснений.
    """
    return f"""\
ЗАДАЧА (ШАГ 1 — только хуки):
Тема поста: «{topic}»

Придумай РОВНО 3 разных варианта хука для этого поста.
Хук — это первые 1-2 строки, которые останавливают скролл.
Каждый вариант — под своим углом подачи (например: личный опыт, провокация, цифра/факт).

ФОРМАТ ВЫВОДА (строго, без вступлений и комментариев):
HOOK_1: <текст первого хука одной-двумя строками>
HOOK_2: <текст второго хука>
HOOK_3: <текст третьего хука>

Выведи ровно три строки HOOK_1, HOOK_2, HOOK_3 и больше ничего."""


def post_format_instruction(selected_hook: str) -> str:
    """ШАГ 2: инструкция полного поста по выбранному хуку (формат §9.1 + §9.3).

    Жёсткие маркеры секций (POST:/CTA:/ХЭШТЕГИ:/ЧЕКЛИСТ:) — для парсинга.
    Тело поста 800-1200 символов (§9.1). Чеклист — по §9.3.
    """
    return f"""\
ЗАДАЧА (ШАГ 2 — полный пост):
Пользователь выбрал этот хук:
«{selected_hook}»

Напиши полный пост Instagram на основе ИМЕННО этого хука.
Строго соблюдай структуру и маркеры секций ниже — не добавляй и не убирай секции.

ФОРМАТ ВЫВОДА (точно по маркерам, каждая секция с новой строки):

{POST_MARKER}
{selected_hook}

<тело поста, 800-1200 символов: разговорно, с конкретикой, цифрами и примерами,
в тоне профиля; раскрой мысль хука и доведи до CTA>

{CTA_MARKER}
<один понятный призыв к действию, без воды; ровно один CTA, не два>

{HASHTAGS_MARKER}
<5-10 релевантных хэштегов в одну строку через пробел, начиная с #;
отдельным блоком, чтобы можно было скопировать отдельно>

{CHECKLIST_MARKER}
✓ Хук останавливает скролл в первые 2 строки
✓ Есть конкретика (цифры / пример / история)
✓ CTA понятен и один (не два разных)
✓ Длина поста: оптимально / короткий / длинный
✓ Хэштеги отделены от текста

В чеклисте для каждого пункта оставь только одну подходящую оценку и, если
пункт не соблюдён, добавь ⚠️ и кратко что исправить. Ничего, кроме этих
четырёх секций ({POST_MARKER} {CTA_MARKER} {HASHTAGS_MARKER} {CHECKLIST_MARKER}), не выводи."""
